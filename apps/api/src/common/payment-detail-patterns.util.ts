// Антифрод-детект реквизитов в исходящих сообщениях с личного Telegram-аккаунта (запрос
// пользователя 2026-08-27) — см. TelegramPersonalService для точки вызова. v1 по явному
// решению пользователя: просто ФАКТ отправки реквизитов, без сверки с "официальным" списком —
// сверка (обнаружение самой подмены, не просто факта) осознанно отложена на будущее.
//
// Форматы, под которые подгонялись паттерны (со слов пользователя, реальные примеры с разных
// проектов): "Sinpe:\nNombre:" — костариканский SINPE Móvil (номер телефона); плюс общий
// гватемальский шаблон банковского перевода (LAFISE/BANRURAL — реальные гватемальские банки,
// см. Nombre/Banco/Tipo de cuenta/Número de cuenta/DNI/Moneda ниже).
//
// 2026-08-29, второй раунд: ~70% срабатываний оказались ложными — "Nombre"/"Cuenta"/"Banco"/
// "Moneda"/"DNI" по отдельности — обычные бытовые испанские слова ("Nombre" = имя, "Cuenta" =
// счёт/аккаунт/"дай счёт" в кафе и т.д.), легко встречаются в обычной переписке безо всякой
// связи с реквизитами. Разделено на "сильные" сигналы (однозначны сами по себе — крипто-адрес,
// SINPE, конкретные банки, устойчивые словосочетания из нескольких слов) и "слабые" одиночные
// слова, которые засчитываются, только если в ОДНОМ сообщении встретилось 2 и более разных слов
// сразу — реальный бланк реквизитов почти всегда перечисляет несколько полей вместе, обычное
// сообщение — почти никогда 2+ из этих слов одновременно. Число из 8 цифр намеренно оставлено
// как самостоятельный (не пороговый) сигнал — явное решение пользователя, несмотря на то что
// оно частично совпадает с форматом телефонных номеров в регионе.

// SINPE Móvil — специфична для Коста-Рики, встречается только у части проектов (запрос
// пользователя 2026-08-29: "по синпе искать надо только в rolando acuna и isabella ramirez").
// Хардкод id здесь — простое, обозримое решение без отдельной схемы/настройки "какие паттерны
// для какого проекта"; если список вырастет далеко за пределы пары проектов, стоит вынести в
// реальное поле в БД, а не расширять этот Set бесконечно.
const SINPE_ONLY_PROJECT_IDS = new Set([
  'cms3h8xkv004nje3l7neyyfv7', // Rolando Acuna
  'cmrtrmch5002tqwjeclcmrmb2', // Isabella Ramirez
]);
const SINPE_PATTERN = /sinpe/i;

// Сильные сигналы (запрос пользователя 2026-08-29) — срабатывают по одному, без порога: крипто-
// адреса, конкретные названия банков и устойчивые многословные фразы почти никогда не встречаются
// случайно в обычной переписке, в отличие от голых одиночных слов ниже.
const STRONG_PATTERNS: RegExp[] = [
  // USDT TRC-20 (Tron) — начинается с T, 34 символа base58 всего.
  /\bT[1-9A-HJ-NP-Za-km-z]{33}\b/,
  // USDT/ETH ERC-20 (Ethereum) — 0x + 40 hex-символов.
  /\b0x[a-fA-F0-9]{40}\b/,
  /\btransferencia bancaria\b/i,
  /\biban\b/i,
  /\blafise\b/i,
  /\bbanrural\b/i,
  /\bnombre del titular\b/i,
  /\btipo de moneda\b/i,
  /\btipo de cuenta\b/i,
  /\bn[uú]mero de cuenta\b/i,
  // Число характерной длины для номеров документов в этих реквизитах — намеренно без порога
  // (явное решение пользователя, "число из 8 цифр оставь", несмотря на совпадение с форматом
  // телефонных номеров в регионе).
  /\b\d{14}\b/,
  /\b\d{8}\b/,
];

// Слабые сигналы — обычные бытовые слова по отдельности, засчитываются только при совпадении
// 2 и более РАЗНЫХ слов в одном сообщении (см. разбор выше).
const WEAK_PATTERNS: RegExp[] = [/\bcuenta\b/i, /\bnombre\b/i, /\bbanco\b/i, /\bdni\b/i, /\bmoneda\b/i];
const WEAK_MATCH_THRESHOLD = 2;

export function containsPaymentDetails(text: string, projectId: string): boolean {
  if (SINPE_ONLY_PROJECT_IDS.has(projectId) && SINPE_PATTERN.test(text)) return true;
  if (STRONG_PATTERNS.some((pattern) => pattern.test(text))) return true;

  const weakMatches = WEAK_PATTERNS.filter((pattern) => pattern.test(text)).length;
  return weakMatches >= WEAK_MATCH_THRESHOLD;
}
